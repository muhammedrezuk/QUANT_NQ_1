/** ترجمة أسماء أعطال بايثون الشائعة — معناها لا اسمها. */
const CRASH_AR: Array<[RegExp, string]> = [
  [/FileNotFoundError|No such file/i, 'ملفّ يحتاجه الفحص غير موجود'],
  [/PermissionError|being used by another process/i, 'ملفّ مشغول ببرنامج آخر فما قدر يفتحه'],
  [/TimeoutExpired|timed out/i, 'الفحص علّق ولم يردّ خلال مهلته'],
  [/UnicodeEncodeError|UnicodeDecodeError/i, 'الطرفيّة ما بتقدر تطبع رمزًا في الرسالة'],
  [/ModuleNotFoundError|ImportError/i, 'قطعة برمجيّة ناقصة ما قدر يستوردها'],
  [/ConnectionRefusedError|10061|Connection refused/i, 'ما في خدمة شغّالة على المنفذ المطلوب'],
  [/JSONDecodeError|Expecting value/i, 'وصله ردّ مشوّه بدل بيانات سليمة'],
  [/KeyError|IndexError|AttributeError|TypeError|ValueError/i, 'خطأ برمجيّ داخل الأداة نفسها'],
]

function explain(r: ToolResult): Explained {
  const out = r.output || ''
  const lines = out.split('\n').map((l) => l.trimEnd()).filter((l) => l.trim() !== '')

  // (١) النواة/اللوحة مطفية — ليست مشكلة فحص أصلًا.
  if (/10061|Connection refused|تعذّرت القراءة من خادم الحوكمة|خطأ اتصال/i.test(out)) {
    return {
      kind: 'core_down',
      headline: '⚠️ ما قدر يوصل للنظام',
      where: 'قبل ما يبدأ الفحص — عند الاتّصال',
      why: 'النواة أو خادم اللوحة مش شغّال الآن.',
      todo: 'شغّل «غرفة القيادة»، وبعدين اكبس الزرّ من جديد.',
    }
  }

  // (٢) الأداة انهارت — عطبٌ في المفكّ لا في المحرّك.
  if (/Traceback \(most recent call last\)/i.test(out)) {
    const frames = [...out.matchAll(/File "([^"]+)", line (\d+)/g)]
    const last = frames[frames.length - 1]
    const file = last ? (last[1].split(/[\\/]/).pop() ?? last[1]) : ''
    const known = CRASH_AR.find(([re]) => re.test(out))
    return {
      kind: 'crashed',
      headline: '🛠️ أداة الفحص نفسها وقعت — مو نظامك',
      where: last ? `توقّف داخل الأداة عند «${file}» سطر ${last[2]}` : 'توقّف داخل الأداة (بلا موضع واضح)',
      why: known ? known[1] : 'سبب تقنيّ داخل الأداة — غير مترجَم، والنصّ الخام تحت.',
      todo: 'هذا لا يقول شيئًا عن سلامة نظامك: الفحص ما وصل لنتيجة أصلًا. '
        + 'بلّغ جلسة اللوحات لتصليح الأداة، وباقي الأزرار تشتغل عادي.',
    }
  }

  // (٣) الفحص اشتغل ووصل لنتيجة — ولقى خللًا حقيقيًّا.
  const marks = lines.filter((l) => /^\s*(❌|✗|🛑)/.test(l) || /\bFAIL\b/.test(l))
  const diffs = out.match(/الاختلافات\s*=\s*(\d+)/)
  const count = diffs ? Number(diffs[1]) : marks.length
  if (!r.ok && (marks.length || (diffs && Number(diffs[1]) > 0))) {
    return {
      kind: 'finding',
      headline: count ? `🛑 الفحص اشتغل لآخره ولقى ${count} خلل` : '🛑 الفحص اشتغل ولقى خللًا',
      where: 'وصل لنهاية الفحص — ما وقع بالطريق',
      why: marks.length
        ? marks.slice(0, 3).map((l) => l.replace(/^\s*[❌✗🛑]\s*/, '• ')).join('\n')
        : 'التفصيل في النصّ الخام تحت.',
      todo: 'هذا خلل حقيقيّ في النظام لا في الأداة. اقرأ السطور فوق، '
        + 'وإذا ما فهمتها ابعتها متل ما هي للجلسة المسؤولة عن القسم.',
    }
  }

  // (٤) فشل بلا علامة مفهومة — يُقال كما هو، ولا يُخترع سبب.
  if (!r.ok) {
    const tail = lines.slice(-3).join('\n')
    return {
      kind: 'unknown',
      headline: '🛑 الفحص فشل — والسبب مش واضح',
      where: lines.length ? 'آخر شي قاله قبل ما يقف:' : 'ما قال شيئًا قبل ما يقف',
      why: tail || 'ما طلع منه أيّ نصّ.',
      todo: 'ابعت هالمربّع متل ما هو لجلسة اللوحات — الأداة ما شرحت سبب فشلها، وهذا عيبٌ فيها.',
    }
  }

  return {
    kind: 'ok',
    headline: '🟢 الفحص اشتغل لآخره وطلع سليم',
    where: '', why: '', todo: '',
  }
}

// ٢٠٢٦-٠٩-٢٢ — `specific`: هل قرأ هذا الملخَّص **مضمون** المخرَج فعلًا، أم
// خرج بجملةٍ عامّة؟ ولم يكن يُميَّز، فظهرت على البطاقة الواحدة جملتان
// متناقضتان مقيستان على الشاشة الحيّة:
//
//   🛑 ذرّة واحدة شغّالة بنسخة أقدم من كودها: 154_الحجم — الكود 2.7.0 …
//   🛑 الفحص فشل — **والسبب مش واضح** وين وقف …
//
// الثانية من مصنّف الفشل العامّ، ويظهر لأنّ `r.ok === false`. والسبب كان
// واضحًا تمامًا — أنا نفسي قرأتُه في السطر الذي قبله. فحكمٌ يقول «لا أعرف»
// فوق حكمٍ يعرف **يهدم الاثنين**: يشكّ المالك في الأوّل ولا ينتفع بالثاني.
//
// فمتى قرأ الملخَّص المضمون، لا يُعرَض مصنِّفُ «لا أعرف» فوقه. ويبقى
// المصنِّف كما هو للانهيار الحقيقيّ — وهو التمييز الذي بُني لأجله:
// «نظامك فيه خلل» مقابل «مفكّي معطوب».
function summarize(id: string, r: ToolResult): { text: string; good: boolean; warn?: boolean; specific?: boolean } {
  const out = r.output
  if (id === 'seal') {
    if (out.includes('سليمة ومطابقة')) return { text: '🟢 النواة سليمة ومطابقة للختم', good: true }
    return { text: '🛑 الختم ما تطابق — افحص فورًا', good: false }
  }
  if (id === 'validator') {
    const m = out.match(/فُحصت\s+(\d+)\s+ذرة[\s\S]*?مخالفات\s+(\d+)\s*·\s*تحذيرات\s+(\d+)/)
    if (m) {
      const bad = Number(m[2])
      return {
        text: bad === 0 ? `🟢 ${m[1]} ذرة — صفر مخالفات` : `🛑 ${m[2]} مخالفة من ${m[1]} ذرة`,
        good: bad === 0,
      }
    }
  }
  if (id === 'boot') {
    // ٢٠٢٦-٠٩-١٦: كان مكتوبًا «212/212» رقمًا ثابتًا في الواجهة، والسجلّ
    // يقول اليوم 228 متوقَّعة و144 بادئة. فكان الزرّ يحكم بعدد من عصرٍ مضى
    // ويعرضه للمالك كأنّه الهدف — **رقمٌ مخترَع في اللوحة لا في النظام**.
    // الآن يُقرأ العددان من مخرَج الفحص نفسه، وإن لم يظهرا قيل ذلك صراحةً.
    const exp2 = out.match(/المتوقع[^\d]*(\d+)/)
    const started = out.match(/بدأت فعليًا[^\d]*(\d+)/)
    const skipped = out.match(/استُبعدت:\s*\[([^\]]*)\]/)
    const nSkip = skipped && skipped[1].trim() ? skipped[1].split(',').length : 0
    if (!exp2 || !started) {
      return { text: '🛑 الفحص ما طلّع عدد الذرّات — اقرأ «شو صار» تحت', good: false }
    }
    const e = Number(exp2[1]); const s = Number(started[1])
    const tail = nSkip ? ` · ${nSkip} مستبعَدة بأمر` : ''
    return s >= e - nSkip
      ? { text: `🟢 الإقلاع: بدأت ${s} من ${e}${tail}`, good: true }
      : { text: `🛑 الإقلاع ناقص: بدأت ${s} من ${e}${tail} — ${e - nSkip - s} ذرّة ما بدأت ولا أُعلن فشلها`, good: false }
  }
  // ٢٠٢٦-٠٩-٢٢ — بلاغ جلسة النواة: ذرّةٌ حيّةٌ بنسخةٍ لا تطابق قرصها، ورفضُ
  // التحميل الحارّ **صامت** (لا `last_error` ولا حالةٌ غير `running` ولا سطرٌ
  // في السجلّ). وقِستُ هذا الزرّ فوجدتُه يكشفها فعلًا — و«الوقتُ الحاضر» عند
  // النواة يأتي من **المانيفست المحمَّل في الذاكرة** لا من قراءةٍ جديدة للقرص،
  // فيصلح مؤشّرَ ما يعمل حقًّا:
  //
  //   154_الحجم   CODE 2.7.0   MANIFEST 2.7.0   RUNTIME 2.5.0   <-- MISMATCH
  //
  // وكان يخرج بحكمٍ عامّ «وُجد شيء» فلا يعرف المالك أيَّ ذرّةٍ ولا ما الفرق.
  // فتُقرأ أسطر المخرَج نفسه: الذرّة ورقماها، ولا يُخترع سببٌ.
  if (id === 'syntax') {
    if (out.includes('SYNTAX_SCAN=CLEAN')) {
      const n = /files=(\d+)/.exec(out)?.[1] ?? '؟'
      return { text: `🟢 ${n} ملفّ كلّهن يُقرأوا — ما في سطر مكسور يوقّف الإقلاع`, good: true, specific: true }
    }
    const bad = out.split('\n').filter((l) => l.trim().startsWith('❌ ') && l.includes(':'))
    if (bad.length) {
      const named = bad.slice(0, 3).map((l) => l.replace(/^\s*❌\s*/, '').trim())
      return {
        text: `🛑 ${bad.length === 1 ? 'ملفّ واحد مكسور' : `${bad.length} ملفّات مكسورة`} — المنصّة ما رح تقلع: `
          + named.join(' · ') + (bad.length > 3 ? ' وغيرها' : '')
          + '. صلّحه صاحب قسمه، وما ينزل ولا سطر بالسجلّ لأنّ الموت قبل المسجّل.',
        good: false, specific: true,
      }
    }
    return { text: '🛑 الفحص ما طلّع نتيجة واضحة — اقرأ «شو صار» تحت', good: false }
  }
  if (id === 'versions') {
    const rows = out.split('\n').filter((l) => l.includes('MISMATCH'))
    if (rows.length === 0) {
      return out.includes('mismatches=0')
        ? { text: '🟢 كل ذرّة: كودها = بطاقتها = المحمَّل بالنواة', good: true }
        : { text: '🛑 الفحص ما طلّع نتيجة واضحة — اقرأ «شو صار» تحت', good: false }
    }
    // كل صفّ: <اسم الذرّة> <كود> <بطاقة> <محمَّل> <-- MISMATCH
    const named = rows.slice(0, 3).map((l) => {
      const p = l.replace('<-- MISMATCH', '').trim().split(/\s+/)
      return p.length >= 4 ? `${p[0]} — الكود ${p[1]} والمحمَّل بالنواة ${p[3]}` : l.trim()
    })
    return {
      text: `🛑 ${rows.length === 1 ? 'ذرّة واحدة' : `${rows.length} ذرّات`} شغّالة بنسخة أقدم من كودها: `
        + named.join(' · ') + (rows.length > 3 ? ' وغيرها' : '')
        + ' — يعني الترقية محفوظة على القرص وما نزلت حيًّا، والنواة لسّا مشغّلة القديم.',
      good: false, specific: true,
    }
  }
  if (id === 'safety') {
    return out.includes('EXECUTION_SAFETY=READY')
      ? { text: '🟢 بوابة سلامة التنفيذ جاهزة', good: true }
      // ٢٠٢٦-٠٩-١٨: كان يُعلن سببًا واحدًا ثابتًا (٥٧٨) لأيّ فشل — وذرّتُه
      // أُرشفت، فصار السبب المعلَن مستحيلًا. السبب الحقيقيّ في مخرَج الفحص
      // نفسه، فيُحال إليه بدل اختراع واحد.
      : { text: '🛑 بوّابة سلامة التنفيذ مش جاهزة — السبب بالتفصيل تحت بـ«شو صار»', good: false }
  }
  if (id === 'security') {
    if (out.includes('SECURITY_STATE=READY')) return { text: '🟢 طبقة الأمان والخزنة جاهزتان', good: true }
    if (out.includes('SECURITY_STATE=NOT_CONFIGURED')) return { text: '🟠 كود الأمان سليم، لكن الخزنة غير منشأة', good: false, warn: true }
    if (out.includes('SECURITY_STATE=DEPENDENCY_MISSING')) return { text: '🟠 مكتبة الأمان ناقصة — شغّل تجهيز البيئة', good: false, warn: true }
    return { text: '🛑 الأمان أو الخزنة غير جاهزين', good: false }
  }
  if (id === 'project') {
    return out.includes('فحص المشروع البنيوي ناجح')
      ? { text: '🟢 فحص المشروع الكامل ناجح', good: true }
      : { text: '🛑 فحص المشروع يحتاج تحقيق', good: false }
  }
  // ٢٠٢٦-١٠-٠٨ (فكّ الأقسام عن القرار، ختم المالك «NQ»): رُفعت من هنا معرّفات العقود التي رُفعت أزرارها (405 · 409 · 166 · القناعة · الميزانيّة · مسار التنفيذ · بقاء الحماية · كتاب الاتّجاه · خانات السعر).
  if (id === 'specs'
      || id === 'shutdown' || id === 'limits'
      || id === 'hotreload' || id === 'deltavis' || id === 'alignment'
      || id === 'switches' || id === 'stoppath'
      || id === 'storagecap' || id === 'snapbutton') {
    // لا نتيجة خضراء جزئية: أي حاجز يسقط = FAIL، حتى لو باقي السطور خضراء.
    const atom = id === 'specs' ? 'بثّ المواصفات'
      : id === 'shutdown' ? 'الإيقاف واللقطة'
      : id === 'limits' ? 'دفاتر الحدود'
      : id === 'hotreload' ? 'بقاء الحماية بالترقية'
      : id === 'deltavis' ? 'رؤية فشل الفرق'
      : id === 'alignment' ? 'مواءمة المرجع'
      : id === 'switches' ? 'أمان المفاتيح'
      : id === 'stoppath' ? 'مسار الإيقاف'
      : id === 'storagecap' ? 'سقوف المخازن' : 'زرّ اللقطة'
    const m = out.match(/الاختلافات\s*=\s*(\d+)/)
    if (!m) return { text: '🛑 الفحص ما كمّل — ما طلع عدّاد الاختلافات', good: false }
    const diffs = Number(m[1])
    if (diffs === 0 && r.ok) return { text: `🟢 عقد ${atom} سليم — حواجز بنيوية + طرف-لطرف، صفر اختلاف`, good: true }
    return { text: `🛑 عقد ${atom} انكسر — ${diffs} اختلاف (شوف الخام)`, good: false }
  }
  if (id === 'telegram') {
    // ثلاث حالات صادقة: حاجز ساقط · حواجز سليمة وناقصها فعل بيدك · سليمة وشغّالة.
    if (!r.ok) return { text: '🛑 حاجز من حواجز المنصّة ساقط — شوف الخام', good: false }
    if (out.includes('مفعّلة · مقترنة · شغّالة')) return { text: '🟢 تلغرام شغّال ومقترن — بوّابته هي بوّابة اللوحة', good: true }
    if (out.includes('غير مفعّلة بعد')) return { text: '🟠 الحواجز سليمة — ناقصها توكن من مدير البوتات', good: false, warn: true }
    if (out.includes('لم تقترن')) return { text: '🟠 مفعّلة — أرسل رمز الاقتران من موبايلك', good: false, warn: true }
    if (out.includes('متوقّفة')) return { text: '🟠 مفعّلة ومقترنة لكنها متوقّفة — شغّل غرفة القيادة', good: false, warn: true }
    return { text: '🟠 حالة غير معروفة — شوف الخام', good: false, warn: true }
  }
  if (['governance', 'files', 'events'].includes(id)) {
    return r.ok
      ? { text: '🟢 الفحص ناجح', good: true }
      : { text: '🛑 الفحص فشل', good: false }
  }
  // ٢٠٢٦-٠٩-٠٩ (أمر المالك «ما ضلّ شي اسمه قسم كريبتو»): سقط هنا فرعُ قراءة
  // حكم فحوص الكريبتو (`crypto_*`) — لا بطاقة تستدعيها بعد رفعها.
  return r.ok
    ? { text: '🟢 خلصت بنجاح', good: true }
    : { text: `🛑 فشلت (رمز ${r.code})`, good: false }
}

