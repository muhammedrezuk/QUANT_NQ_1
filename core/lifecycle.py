"""
Core.lifecycle — سياسة دورة حياة الذرة الموحّدة (فتحة النواة V2.0 — ورقة ٠٦).

الجذر: نداء دورة حياة ذرة (`initialize/start/stop/shutdown`) غير موثوق — قد يعلّق
للأبد فيجمّد المحرّك كلّه (المحرّك محميّ بمهلة أثناء الإقلاع فقط، ومكشوف في التحميل
الحار وإعادة التشغيل وزرّ الإيقاف). الحل: **مهلة موحّدة + دالة لفّ واحدة**
تستعملها كل المسارات خارج الإقلاع، فلا تتكرّر السياسة ولا تفلت جهة رابعة مستقبلًا.

عند التجاوز يُرفع `LifecycleTimeout` حاملًا اسم الطور — والمستدعي يسم الذرة FAILED
بسبب مميّز (`LIFECYCLE_TIMEOUT:<phase>`) فتميّز طبقة ٢ «مات بمهلة» عن «انهار» بلا
حالة مختومة جديدة، ثم يكمل المحرّك جولته.

⚠️ **٢٠٢٦-٠٩-٢٣ — حدُّ هذه المهلة، مقيسًا. لا تُقرأ على أنّها تحرس ما لا تحرسه.**

`asyncio.wait_for` يُلغي عند **نقطة انتظار**. وكوروتينٌ يعمل عملًا متزامنًا
(SQLite بلا خيط · حلقةٌ حاسبة · قراءةُ ملفّ) لا يبلغ نقطةَ انتظارٍ أبدًا، فلا
يُلغى ويمضي إلى آخره — **وحلقةُ التداول مجمّدةٌ طوال ذلك**.

    المقيس ٢٠٢٦-٠٩-٢٣:  580.initialize = 31,474 م.ث   والسقف 30,000
    تجاوزه ولم يُرفع `LifecycleTimeout` — لأنّ النداء لم يتنازل قطّ.

فالمهلة تحرس **التعليق عند انتظار**، ولا تحرس **تجميد الحلقة**. والنواة لا
تملك أن تجعل كودَ غيرها يتنازل: نقلُ `initialize`/`start` إلى خيطٍ آخر يكسر
`create_task` و`Lock` في ٢٦ ذرّة (موثّق في ‎1.31.0‎). فما تملكه — وما تفعله
هنا — أن **تقيس الحجز وتسمّي صاحبه**، فلا يبقى «مَن جمّد الحلقة» سؤالًا.

وقبل هذا لم يكن في المشروع كلِّه رقمٌ يقول ذلك: ٥٨٠ جمّدت الحلقة عند كلّ
ترقيةٍ حارّة، ولم يظهر في أيّ سجلّ ولا عدّاد.
"""

from __future__ import annotations

import asyncio
import logging
import time
from typing import Awaitable

LIFECYCLE_TIMEOUT_S = 30.0

#: فوقه يُعلَن أنّ النداء حجز الحلقة. لا يُسقط ذرّةً ولا يغيّر سلوكًا —
#: يسمّي فقط. وواحدُ ثانية سخيٌّ عمدًا: ميزانيّة المعالج ميلي ثوانٍ،
#: فما بلغ الثانية ليس بطئًا بل حجزًا.
LOOP_BLOCK_WARN_S = 1.0

_log = logging.getLogger("quant_nq.core.lifecycle")

class LifecycleTimeout(Exception):
    """تجاوز نداء دورة حياة المهلة المسموحة — سبب مميّز لطبقة ٢."""

    def __init__(self, phase: str) -> None:
        self.phase = phase
        super().__init__(f"LIFECYCLE_TIMEOUT:{phase}")


async def call_lifecycle(
    awaitable: Awaitable,
    phase: str,
    *,
    timeout: float = LIFECYCLE_TIMEOUT_S,
    subject: str = "",
) -> None:
    """ينفّذ نداء دورة حياة بسقف زمني، **ويقيس ما حجزه من الحلقة**.

    تجاوز المهلة = `LifecycleTimeout(phase)`. وأي استثناء آخر من الذرة يمرّ
    كما هو ليعالجه المستدعي.

    `subject` اسمُ صاحب النداء (رقم الذرّة عادةً) — يُمرَّر حيث يُعرف، فيصير
    سطرُ الإعلان قابلًا للتصرّف. وغيابه لا يعطّل القياس.

    القياس بزمن الحائط لا بزمن المعالج: حين لا يتنازل النداء، **زمنُ الحائط
    هو مدّة تجميد الحلقة بعينها**.
    """
    started = time.perf_counter()
    try:
        await asyncio.wait_for(awaitable, timeout=timeout)
    except asyncio.TimeoutError as exc:
        raise LifecycleTimeout(phase) from exc
    finally:
        # ⚠️ لا دفترَ هنا: أُضيف `worst_block_s`/`blocked_calls` في ‎1.37.0‎
        # ولم يقرأهما مسارٌ واحد — وهو عينُ العطب الذي فُتحت له ‎1.38.0‎.
        # سطرُ السجلّ هو الأداة، وهو يُقرأ فعلًا.
        elapsed = time.perf_counter() - started
        if elapsed >= LOOP_BLOCK_WARN_S:
            _log.error(
                "نداء دورة الحياة حجز الحلقة: %s %s — %.3f ث (السقف لا يقطع "
                "نداءً لا يتنازل)",
                subject or "?", phase, elapsed,
            )
