"""٥٥٥ — خانة الإعدادات التحليليّة لكلّ (رمز × جهة)، ومستويات القرار.

v1.24.1 (٢٠٢٦-١٠-٠١، ختم `Nq`): نُقلت من `atom.py` **حرفيًّا** كي ينزل تحت حدّ
المادة 9 (٤٠٠ سطر فعليّ). كلّ دالّةٍ هنا كانت تابعًا في صنف الذرّة، والفرقُ
الوحيد أنّ `self` صار `atom` — والتوابعُ بأسمائها باقيةٌ في `atom.py` تُحيل إلى
هنا. لا سلوك جديد، ولا عدّاد ولا سبب ولا نصّ تغيّر.
"""
from __future__ import annotations

import time
from typing import Any

from shared.trade_setup import is_alive, validate_setup, OK as SETUP_OK
from entry_request_sizing import _number


async def on_setup(atom, payload: dict) -> None:
    """يحفظ آخر إعدادٍ صالح لكل **(رمز × جهة)**.

    🔴 ٢٠٢٦-٠٩-١٨ — كانت الخانة لكلّ رمزٍ وحده، و٤٠٦ و٤١٠ ينشران
    إعدادين **متعاكسين في اللحظة نفسها** على الرمز الواحد. فآخرُ واصلٍ
    يدهس سابقه، ثمّ يأتي الأمر بجهةٍ لا تطابقه فتردّ `_setup_levels`
    فراغًا ويسقط النداء إلى `FALLBACK_513` — **فوقفُ التحليل لا يصل
    الأمر أصلًا، لا لأنّه رديء بل لأنّه دُهس قبل أن يُطلب**.

    والمقيس عند جلسة ٤٠٠–٤٥٠: `إعداد_مخالف = 1,189`. وآخر صفقةٍ حتّى
    بلاغهم خرجت بوقفٍ احتياطيّ لهذا السبب بعينه.

    ولا منطق جديد ولا حكم: الخانة تصير لكلّ جهة، فإعداد الشراء لا يدهس
    إعداد البيع. ومن لا يجد إعداد جهته يسقط إلى الاحتياطيّ كما كان.
    """
    if not atom._running or not isinstance(payload, dict):
        return
    # 🔴 ٢٠٢٦-٠٩-١٩ — كان الردّ هنا `return` صامتًا: كلُّ إعدادٍ لا
    # يجتاز الفحص يسقط بلا عدّادٍ ولا سبب. فشارتي تقول «خانات=0»
    # ولا تقول هل وصل شيء أصلًا ولا لماذا رُدّ — وهو الفرق بين
    # «المنبع جافّ» و«المنبع يُرسل وأنا أردّ». يومٌ كامل بلا صفقة
    # ولا سطرٌ واحد يقول أين ماتت.
    verdict = validate_setup(payload)
    if verdict != SETUP_OK:
        atom._setup_refused += 1
        atom._refuse_why[verdict] = atom._refuse_why.get(verdict, 0) + 1
        atom._last_refused = "%s %s %s" % (
            str(payload.get("symbol") or "?"),
            str(payload.get("side") or "?"), verdict)
        return
    atom._setup_taken += 1
    symbol = str(payload.get("symbol") or "").strip().upper()
    side = str(payload.get("side") or "").strip().lower()
    if symbol and side:
        # 🔴 ٢٠٢٦-٠٩-١٩ — لحظةُ الوصول تُحفظ مع الإعداد.
        #
        # الخانة تحمل إعدادًا حتّى ينقضي أجلُه (١٨٠٠ ث)، فيُنفَّذ بعد
        # نصف ساعةٍ من ولادته وقد تغيّر السوق **وسُحب مصدرُه**. ووقع
        # اليوم مقيسًا: بلّغت جلسة ٤٠٠-٤٥٠ أنّها أوقفت ٤٠٦ و٤١٠ ومنعت
        # ٤٠٥ على الذهب والباوند، وبعد الإيقاف خرج من مخزوني أمران
        # بـ`406:range_edge` وأمران على `XAUUSD` — من إعداداتٍ مخزّنةٍ
        # قبل التبليغ.
        #
        # فيُحفظ زمن الوصول ويُعلَن أقدمُ إعدادٍ في الشارة، ليُرى
        # البائتُ قبل أن يُنفَّذ. [[setup-cached-by-ttl-only-room-collapses]]
        row = dict(payload)
        row["_received_at"] = time.monotonic()
        atom._setups[(symbol, side)] = row


def levels_on_decision(atom, payload: dict[str, Any]):
    """مستويات القرار إن حملها معه — العقد المتّفق عليه ٢٠٢٦-٠٩-٢٣.

    **العلّة التي يغلقها:** كان القرارُ ووقفُه في مجرَيين يُوصَلان
    بالمطابقة على (رمز × جهة). وبيّنت جلسة التحليل أنّهما ليسا
    متوازيَين فحسب بل بإيقاعَين مختلفَين بثلاث مراتب: القرارُ يُبنى من
    `strategy.*.state` المنشورة على **كلّ تقييم**، والإعدادُ يُنشر من
    الملفّ نفسه عند `|z|≥3` فقط ولا يمرّ بمسار القرار البتّة. فالجهةُ
    التي تصلني في القرار والجهةُ التي في خانتي مولودتان من فمَين.

    والمقيس يومَها: ‎820‎ من ‎832‎ قرارًا ماتت `NO_STOP_FOR_SIDE`،
    ‎819‎ منها «بلا إعدادٍ لهذه الجهة».

    **والعقد أربعةُ حقول تُضاف ولا يُحذف شيء**، بأسماء
    `shared/trade_setup.py` نفسها فلا ترجمة ولا اشتقاق:
    `invalidation_price` · `target_price` · `setup_id` ·
    `invalidation_source`. يختمها ٤٦٦ على قراره المعتمد (هو موضعُ
    القطع: يبني قاموسًا جديدًا فيُسقط ما فوقه)، و٤٦٧ يمرّرها بلا سطرٍ
    جديد لأنّ `body = dict(payload)` ينسخ الوارد كلَّه.

    ⚠️ **وهذا يُغلق عطبَين لا الفجوةَ كلَّها** — أمانةً كما قالها
    شريكي: ٤٦٦ يبحث في الخانة نفسها باللحظة نفسها، فما لا أجده اليوم
    لا يجده غدًا. المكسبُ أنّ الإعداد يُختَم لحظةَ صلاحيّته:
    **يموت الأجلُ** (لا تنفيذَ بعد نصف ساعةٍ وقد مات مصدرُه — عطب
    ٠٩-١٩) **ويموت الاستهلاك** (لا مخزونَ يُتنازَع عليه). أمّا العدد
    فلا يُغلق إلّا بأن يصير الطرفُ النادر مسموعًا في مسار القرار، وذاك
    شغلُ التحليل في ‎400-466‎.

    والغيابُ يسقط إلى سلوك اليوم بحرفه — فلا انقطاع لحظةَ النشر، ولا
    يلزم إقلاعٌ متزامنٌ للقسمين.
    """
    if not isinstance(payload, dict):
        return None
    level = _number(payload.get("invalidation_price"))
    if level is None or level <= 0.0:
        return None
    atom._levels_inline += 1
    return {"setup_id": payload.get("setup_id"),
            "invalidation_price": level,
            "target_price": payload.get("target_price"),
            "invalidation_source": payload.get("invalidation_source")}


def setup_levels(atom, symbol: str, side: str):
    """مستويا التحليل لهذا الرمز والاتجاه — أو لا شيء.

    الوقف من التحليل حصرًا بحكم المالك ٢٠٢٦-٠٩-١١. ولا يُخترع بديل:
    الغائب يبقى غائبًا ويسقط النداء إلى الاحتياطيّ المعلن.
    """
    key = (str(symbol).strip().upper(), str(side).strip().lower())
    setup = atom._setups.get(key)
    if not setup:
        # غيابٌ يُعدّ: إمّا لم يصل إعدادٌ لهذه الجهة قطّ، وإمّا وصل
        # ومات. والفرق بينهما وبين «وصل ودُهس» هو ما كان مخفيًّا.
        atom._setup_missing += 1
        return None
    if not is_alive(setup):
        atom._setup_dead += 1
        return None
    return setup
