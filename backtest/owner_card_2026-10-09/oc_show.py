# -*- coding: utf-8 -*-
import sys, json, os
sys.stdout.reconfigure(encoding="utf-8")
HERE = os.path.dirname(os.path.abspath(__file__))
R = json.load(open(os.path.join(HERE, "results.json"), encoding="utf-8"))
J = lambda x: json.dumps(x, ensure_ascii=False)
for lab in ("لندن|نقاط", "أمريكا|نقاط", "لندن|نسبيّ", "أمريكا|نسبيّ"):
    S = R[lab]
    print("=====", lab, "جلسات", S["جلسات"], "ثبات", J(S["ثبات_الشبكة"]))
    print("دقّة الجهة", J(S["دقّة_الجهة"]))
    print("-- العرّاف (8):")
    for r in S["العرّاف"]:
        print("  ", r["التركيبة"], "تعلّم", J(r["تعلّم"]), "| اختبار", J(r["اختبار"]))
    print("-- ج0 (8):")
    for r in S["الشبكة"]:
        if r["التركيبة"].startswith("ج0"):
            print("  ", r["التركيبة"], "تعلّم", r["تعلّم"].get("R/صفقة"), r["تعلّم"].get("n"), "| اختبار", r["اختبار"].get("R/صفقة"), r["اختبار"].get("n"))
    D = S.get("تشخيص_المختارة", {})
    for k in ("التركيبة", "عدّاد", "شراء", "بيع", "الجهات_بالعيار_نفسه", "ج0_بحسب_العرّاف", "حجم_الوقف", "الإمساك",
              "إزاحة_دقيقة", "ضعف_الكلفة", "نهاية_الدخول_القصوى", "إغلاق_قسريّ_16:00_نيويورك_للعلم", "حساسيّة_للعلم", "سنوات_كلّه"):
        if k in D:
            print("--", k, J(D[k]))
print("===== نافذة سجلّه", J(R.get("نافذة_سجلّه_05:30–07:00غ")))
print("===== المقارنة", J(R["المقارنة_بسجلّه"]["الملخّص_من_33"]))
